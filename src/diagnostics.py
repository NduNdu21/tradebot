"""Post-mortem diagnostics on the failed primary (development data only).

The strategy rules and the hold-out are untouched; nothing here selects or tunes anything.

    python -m src.diagnostics            # writes the "Diagnostics" section of docs/backtests.md

1. The baseline cell (K=3, min_bars=5, primary settings) with spread, slippage and
   financing all zero: how much of the loss is costs?
2. Five randomly chosen trades from the baseline run, with every price needed to
   check them against a chart.
3. The random-entry control run in-sample on the baseline cell (1,000 draws): where
   does the strategy's mean R fall in the random distribution?
"""
import argparse
import os
import pickle
from concurrent.futures import ProcessPoolExecutor

import numpy as np
import pandas as pd

from src.backtest import Engine, load_data
from src.data import DEV_START, HOLDOUT_START
from src.experiments import (PRIMARY, RANDOM_RUNS, RandomEntryStrategy, _STATE, _cache_path, _init_worker, _r,
                             cell_result, entry_hours, in_window, random_plan, setup_table, summarize, write_report)
from src.setups import FIB, FibStrategy, build_h1

BASELINE = (3, 5)
MARKERS = ("<!-- diagnostics:start -->", "<!-- diagnostics:end -->")
SAMPLE_SEED = 2026
SAMPLE_SIZE = 5


def zero_spread(df):
    """Bid and ask both set to the mid, field by field. Mid prices (and so every signal) don't change."""
    out = df.copy()
    for f in "ohlc":
        mid = (df[f"bid_{f}"] + df[f"ask_{f}"]) / 2
        out[f"bid_{f}"] = mid
        out[f"ask_{f}"] = mid
    return out


def zero_cost_config():
    """Primary config with no slippage. Financing is removed by reading the financing-off column."""
    cfg = PRIMARY.config()
    cfg.slippage_pips = {pair: 0.0 for pair in cfg.slippage_pips}
    return cfg


def dev_years(start=DEV_START, end=HOLDOUT_START):
    """Consecutive one-year windows covering development: the random control's 'same year'."""
    out, s = [], start
    while s < end:
        out.append((s, min(s + pd.DateOffset(years=1), end)))
        s = s + pd.DateOffset(years=1)
    return out


def with_year_windows(setups):
    """Label each setup with the development year of its first fill, for random_plan."""
    years = dev_years()
    starts = [next(s for s, e in years if s <= t < e) for t in setups.first_fill]
    ends = [dict(years)[s] for s in starts]
    return setups.assign(cell=[BASELINE] * len(setups), test_start=starts, test_end=ends)


def run_baseline(data, h1, config):
    """One engine run of the baseline cell. Returns (dev setups, dev legs, strategy log)."""
    strategy = FibStrategy(h1, PRIMARY.params(*BASELINE))
    engine = Engine(data, strategy, config).run()
    result = cell_result(engine)
    legs = in_window(result["legs"], DEV_START, HOLDOUT_START, "entry_time")
    return in_window(setup_table(result["legs"]), DEV_START, HOLDOUT_START), legs, strategy.log


def frozen_levels(log):
    """{(pair, setup id): levels at the first fill}, from the strategy's decision log."""
    return {(entry[1], entry[3]): entry[4] for entry in log if entry[2] == "freeze"}


def sample_trades(legs, n=SAMPLE_SIZE, seed=SAMPLE_SEED):
    return legs.sample(n=n, random_state=seed).sort_values("entry_time")


def _run_random_in_sample(job):
    seed, plan, hours = job
    strategy = RandomEntryStrategy(_STATE["h1"], plan, hours, np.random.default_rng(seed))
    engine = Engine(_STATE["data"], strategy, PRIMARY.config()).run()
    setups = setup_table(cell_result(engine)["legs"])
    out = {f"mean_{m}": setups[f"r_{m}"].mean() for m in ("on", "off", "capped")}
    out.update(n=len(setups), redraws=strategy.redraws, dropped=strategy.dropped)
    return out


def run_random_in_sample(plan, hours, workers, runs, fresh=False):
    path = _cache_path(f"random_in_sample_k{BASELINE[0]}_m{BASELINE[1]}_{runs}")
    if not fresh and os.path.exists(path):
        with open(path, "rb") as f:
            return pickle.load(f)
    print(f"{runs} in-sample random-entry runs on {workers} workers")
    jobs = [(seed, plan, hours) for seed in range(runs)]
    with ProcessPoolExecutor(workers, initializer=_init_worker) as pool:
        results = pd.DataFrame(list(pool.map(_run_random_in_sample, jobs, chunksize=4)))
    with open(path, "wb") as f:
        pickle.dump(results, f)
    return results


def _leg_stats(legs, column):
    g = legs.groupby("leg")
    return {leg: ((d[column] > 0).mean() * 100, d[column].mean()) for leg, d in g}


def _price(pair, x):
    return f"{x:.3f}" if pair.endswith("JPY") else f"{x:.5f}"


def build_report(base, zero, sample, levels, random_results):
    base_s, base_legs = base
    zero_s, zero_legs = zero
    b, z = summarize(base_s.r_on), summarize(zero_s.r_off)
    L = [MARKERS[0], "", "## Diagnostics (development data only; generated by `python -m src.diagnostics`)", "",
         "Post-mortem on the failed primary. The strategy rules are unchanged and the hold-out is untouched; nothing "
         "here selects or re-tunes anything. Baseline cell: K=3, min_bars=5, mode a, TP2, 96-bar limit, "
         "running-extreme anchoring, Friday close on. Period 2016-11-14 → 2024-11-13.", "",
         "### 1. Baseline cell with zero costs", "",
         "Spread zero (bid = ask = mid; signals use mid prices, so they don't change), slippage zero, financing "
         "zero (the financing-off column).", "",
         "| Run | Setups | Mean R per setup | SE | Leg 1 win % / mean R | Leg 2 win % / mean R |",
         "|---|---|---|---|---|---|"]
    for name, s, legs, col, stats in (("With costs (financing on)", base_s, base_legs, "r_on", b),
                                      ("Zero costs", zero_s, zero_legs, "r_off", z)):
        ls = _leg_stats(legs, col)
        cells = " | ".join(f"{ls[k][0]:.1f}% / {_r(ls[k][1])}" if k in ls else "—" for k in (1, 2))
        L.append(f"| {name} | {stats['n']} | {_r(stats['mean'])} | {stats['se']:.3f} | {cells} |")
    L += ["", f"Costs account for {_r(b['mean'] - z['mean'])}R of the {_r(b['mean'])}R per setup. "
          f"Without any costs the baseline is {_r(z['mean'])}R per setup "
          f"({abs(z['mean'] / z['se']):.1f} standard errors {'below' if z['mean'] < 0 else 'above'} zero).", "",
          "### 2. Five random trades from the baseline run (to check on a chart)", "",
          f"Drawn with seed {SAMPLE_SEED} from all {len(base_legs)} baseline legs. Times are UTC candle times "
          "(M5 open). Longs enter at the ask and exit at the bid; shorts the opposite. Stops pay 0.5 pip "
          "(EUR_USD) or 1 pip (GBP_JPY) slippage. Swing origin and extreme are H1 mid prices; the origin time is "
          "the H1 bar of the confirmed swing low (high for sells). R is the leg's P&L over its own planned risk.", ""]
    for i, t in enumerate(sample.itertuples(), 1):
        lv = levels.get((t.pair, t.setup_id))
        side, origin_time = t.setup_id
        p = lambda x: _price(t.pair, x)
        if lv is not None:
            swing = (lv.tp2 - lv.tp1) / (FIB["tp2"] - FIB["tp1"])
            geometry = (f"swing origin {p(lv.tp2 - swing)} (H1 bar {origin_time:%Y-%m-%d %H:%M}), extreme {p(lv.tp2)}; "
                        f"leg 1 {p(lv.leg1)}, leg 2 {p(lv.leg2)}, stop {p(lv.stop)}, TP2 {p(lv.tp2)}")
        else:
            geometry = f"swing origin H1 bar {origin_time:%Y-%m-%d %H:%M}"
        L += [f"**{i}. {t.pair} {t.side}, leg {t.leg}.** {geometry}.", "",
              "| Entry time | Entry price | Units | Stop | Target | Exit time | Exit price | Exit | R (financing off) "
              "| R (on) |", "|---|---|---|---|---|---|---|---|---|---|",
              f"| {t.entry_time:%Y-%m-%d %H:%M} | {p(t.entry_price)} | {t.units:,} | {p(t.stop)} | {p(t.target)} "
              f"| {t.exit_time:%Y-%m-%d %H:%M} | {p(t.exit_price)} | {t.exit_reason} | {_r(t.r_off)} | {_r(t.r_on)} |",
              ""]
    strat = b["mean"]
    r = random_results.mean_on
    pct = (r < strat).mean() * 100
    L += ["### 3. Random-entry control, in-sample on the baseline cell", "",
          f"{len(random_results)} runs. Each run re-enters every baseline setup ({b['n']}) at market at a random H1 "
          "open in the same development year (2016-11-14 + n years), the hour drawn from that pair's real "
          "first-fill hours (UTC), with the same side, legs and stop/target distances, through the same engine "
          "and primary config (spread, slippage, financing, caps, Friday close, one setup per pair).", "",
          "| | Mean R per setup (financing on) |", "|---|---|"]
    for name, val in (("Minimum", r.min()), ("5th percentile", r.quantile(0.05)), ("Median", r.median()),
                      ("95th percentile", r.quantile(0.95)), ("Maximum", r.max())):
        L.append(f"| Random: {name.lower()} | {_r(val)} |")
    L += [f"| **Strategy (baseline cell)** | **{_r(strat)}** |", "",
          f"The strategy's mean R is at the **{pct:.1f}th percentile** of the random distribution: "
          f"{int((r < strat).sum())} of {len(r)} random runs did worse. "
          f"Random setups per run: mean {random_results.n.mean():.0f} of {b['n']} "
          f"(redrawn because the pair was busy: {random_results.redraws.mean():.0f}; dropped: "
          f"{random_results.dropped.mean():.1f}).", "", MARKERS[1]]
    return "\n".join(L)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--workers", type=int, default=max(1, (os.cpu_count() or 2) - 1))
    parser.add_argument("--random-runs", type=int, default=RANDOM_RUNS)
    parser.add_argument("--fresh", action="store_true")
    args = parser.parse_args()

    data = load_data()            # development only: the hold-out is cut off in src.data
    h1 = build_h1(data)
    base_s, base_legs, log = run_baseline(data, h1, PRIMARY.config())
    zero_data = {k: zero_spread(v) for k, v in data.items()}
    zero_s, zero_legs, _ = run_baseline(zero_data, h1, zero_cost_config())

    plan = random_plan(with_year_windows(base_s), {BASELINE: base_legs})
    random_results = run_random_in_sample(plan, entry_hours(base_s), args.workers, args.random_runs, args.fresh)

    text = build_report((base_s, base_legs), (zero_s, zero_legs), sample_trades(base_legs), frozen_levels(log),
                        random_results)
    write_report(text, markers=MARKERS)
    print("diagnostics written to docs/backtests.md")


if __name__ == "__main__":
    main()
